import { expect, test } from 'vitest'
import { withRo } from './korean'

test.each([
  ['2분', '2분으로'],
  ['2분 21초', '2분 21초로'],
  ['1시간', '1시간으로'],
  ['짧은 해설', '짧은 해설로'],
  ['자동', '자동으로'],
  ['대사만', '대사만으로'],
  ['1:20', '1:20으로'],
  ['1:24', '1:24로'],
  ['1:23', '1:23으로'],
  ['1:27', '1:27로'],
  ['50퍼센트', '50퍼센트로'],
  ['처음', '처음으로'],
])('%s → %s', (word, expected) => {
  expect(withRo(word)).toBe(expected)
})
