def to_ms(ts: str) -> int:
    """'MM:SS', 'H:MM:SS', 'MM:SS.s' → 밀리초."""
    sec = 0.0
    for x in str(ts).strip().split(":"):
        sec = sec * 60 + float(x)
    return int(round(sec * 1000))
