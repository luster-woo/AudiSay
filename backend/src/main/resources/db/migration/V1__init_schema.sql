CREATE EXTENSION IF NOT EXISTS btree_gist;  -- 장면 구간 겹침 금지(EXCLUDE)에 필요

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    name VARCHAR(50) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'GENERAL',
    verified_at TIMESTAMPTZ,
    withdrawn_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT ck_users_1 CHECK (role IN ('GENERAL', 'VISUALLY_IMPAIRED', 'ADMIN')),
    CONSTRAINT ck_users_verified CHECK (role <> 'VISUALLY_IMPAIRED' OR verified_at IS NOT NULL)
);

CREATE TABLE user_settings (
    user_id BIGINT NOT NULL,
    detail_level SMALLINT NOT NULL DEFAULT 2,
    narration_mode VARCHAR(20) NOT NULL DEFAULT 'AUTO',
    speech_rate NUMERIC(2,1) NOT NULL DEFAULT 1.0,
    sound_mix VARCHAR(30) NOT NULL DEFAULT 'DIALOGUE_AND_NARRATION',
    subtitle_reading VARCHAR(20) NOT NULL DEFAULT 'DIFFERENT_ONLY',
    original_volume SMALLINT NOT NULL DEFAULT 100,
    voice_code VARCHAR(50),
    seek_step_sec SMALLINT NOT NULL DEFAULT 10,
    summary_mode VARCHAR(10) NOT NULL DEFAULT 'ASK',
    high_contrast BOOLEAN NOT NULL DEFAULT FALSE,
    font_size_level SMALLINT NOT NULL DEFAULT 3,
    tutorial_completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_user_settings PRIMARY KEY (user_id),
    CONSTRAINT ck_user_settings_1 CHECK (detail_level BETWEEN 1 AND 3),
    CONSTRAINT ck_user_settings_2 CHECK (narration_mode IN ('AUTO', 'WITH_VIDEO', 'PAUSE_AFTER')),
    CONSTRAINT ck_user_settings_3 CHECK (speech_rate BETWEEN 0.5 AND 2.5),
    CONSTRAINT ck_user_settings_4 CHECK (sound_mix IN ('DIALOGUE_ONLY', 'DIALOGUE_AND_NARRATION')),
    CONSTRAINT ck_user_settings_5 CHECK (subtitle_reading IN ('ALL', 'DIFFERENT_ONLY', 'OFF')),
    CONSTRAINT ck_user_settings_6 CHECK (original_volume BETWEEN 0 AND 100),
    CONSTRAINT ck_user_settings_7 CHECK (seek_step_sec IN (5, 10, 30)),
    CONSTRAINT ck_user_settings_8 CHECK (summary_mode IN ('ASK', 'ALWAYS', 'NEVER')),
    CONSTRAINT ck_user_settings_9 CHECK (font_size_level BETWEEN 1 AND 5)
);

CREATE TABLE videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_type VARCHAR(10) NOT NULL,
    youtube_video_id VARCHAR(20),
    uploader_id BIGINT,
    title VARCHAR(300) NOT NULL,
    source_description TEXT,
    channel_title VARCHAR(200),
    thumbnail_url VARCHAR(500),
    duration_sec INTEGER NOT NULL,
    category VARCHAR(20),
    visibility VARCHAR(10) NOT NULL DEFAULT 'PRIVATE',
    status VARCHAR(15) NOT NULL DEFAULT 'REGISTERED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_videos PRIMARY KEY (id),
    CONSTRAINT uq_videos_youtube_video_id UNIQUE (youtube_video_id),
    CONSTRAINT ck_videos_1 CHECK (source_type IN ('YOUTUBE', 'UPLOAD')),
    CONSTRAINT ck_videos_2 CHECK (category IS NULL OR category IN ('EDUCATION', 'COOKING', 'GAME', 'MUSIC', 'SCIENCE_IT', 'NEWS', 'ENTERTAINMENT', 'SPORTS', 'ETC')),
    CONSTRAINT ck_videos_3 CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    CONSTRAINT ck_videos_4 CHECK (status IN ('REGISTERED', 'UPLOADING', 'READY', 'UNAVAILABLE')),
    CONSTRAINT ck_videos_5 CHECK (duration_sec >= 0),
    CONSTRAINT ck_videos_source CHECK ((source_type = 'YOUTUBE' AND youtube_video_id IS NOT NULL AND uploader_id IS NULL) OR (source_type = 'UPLOAD' AND youtube_video_id IS NULL AND uploader_id IS NOT NULL))
);

CREATE TABLE video_uploads (
    video_id BIGINT NOT NULL,
    original_key VARCHAR(500) NOT NULL,
    s3_upload_id VARCHAR(255),
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(30) NOT NULL,
    size_bytes BIGINT NOT NULL,
    upload_status VARCHAR(15) NOT NULL DEFAULT 'INITIATED',
    playback_key VARCHAR(500),
    playback_format VARCHAR(5),
    transcode_status VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    CONSTRAINT pk_video_uploads PRIMARY KEY (video_id),
    CONSTRAINT uq_video_uploads_s3_upload_id UNIQUE (s3_upload_id),
    CONSTRAINT ck_video_uploads_1 CHECK (content_type IN ('video/mp4', 'video/quicktime', 'video/webm')),
    CONSTRAINT ck_video_uploads_2 CHECK (size_bytes > 0),
    CONSTRAINT ck_video_uploads_3 CHECK (upload_status IN ('INITIATED', 'UPLOADING', 'COMPLETED', 'ABORTED')),
    CONSTRAINT ck_video_uploads_4 CHECK (playback_format IS NULL OR playback_format IN ('MP4', 'HLS')),
    CONSTRAINT ck_video_uploads_5 CHECK (transcode_status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED'))
);

CREATE TABLE favorites (
    user_id BIGINT NOT NULL,
    video_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_favorites PRIMARY KEY (user_id, video_id)
);

CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    video_id BIGINT NOT NULL,
    requested_by BIGINT NOT NULL,
    job_type VARCHAR(15) NOT NULL DEFAULT 'GENERATE',
    pipeline VARCHAR(15) NOT NULL,
    status VARCHAR(15) NOT NULL DEFAULT 'QUEUED',
    current_stage VARCHAR(15),
    progress SMALLINT NOT NULL DEFAULT 0,
    error_code VARCHAR(50),
    queued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    CONSTRAINT pk_jobs PRIMARY KEY (id),
    CONSTRAINT ck_jobs_1 CHECK (job_type IN ('GENERATE', 'REGENERATE')),
    CONSTRAINT ck_jobs_2 CHECK (pipeline IN ('GEMINI_URL', 'LOCAL')),
    CONSTRAINT ck_jobs_3 CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED')),
    CONSTRAINT ck_jobs_4 CHECK (current_stage IS NULL OR current_stage IN ('PREPARE', 'DESCRIBE', 'MERGE', 'TTS')),
    CONSTRAINT ck_jobs_5 CHECK (progress BETWEEN 0 AND 100)
);

CREATE TABLE job_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id BIGINT NOT NULL,
    chunk_index INTEGER NOT NULL,
    start_ms INTEGER NOT NULL,
    end_ms INTEGER NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    attempts SMALLINT NOT NULL DEFAULT 0,
    context_summary TEXT,
    last_error TEXT,
    worker_id VARCHAR(100),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_job_chunks PRIMARY KEY (id),
    CONSTRAINT uq_job_chunks_job_id_chunk_index UNIQUE (job_id, chunk_index),
    CONSTRAINT ck_job_chunks_1 CHECK (status IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED', 'DEAD')),
    CONSTRAINT ck_job_chunks_2 CHECK (end_ms > start_ms),
    CONSTRAINT ck_job_chunks_3 CHECK (attempts BETWEEN 0 AND 3)
);

CREATE TABLE generation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    video_id BIGINT NOT NULL,
    job_id BIGINT,
    result VARCHAR(15) NOT NULL,
    counted BOOLEAN NOT NULL,
    request_date DATE NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_generation_requests PRIMARY KEY (id),
    CONSTRAINT ck_generation_requests_1 CHECK (result IN ('NEW_JOB', 'JOINED_JOB', 'REUSED', 'REJECTED'))
);

CREATE TABLE descriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    video_id BIGINT NOT NULL,
    job_id BIGINT NOT NULL,
    status VARCHAR(15) NOT NULL DEFAULT 'GENERATING',
    summary_text TEXT,
    summary_audio_key VARCHAR(500),
    summary_duration_ms INTEGER,
    model_name VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_descriptions PRIMARY KEY (id),
    CONSTRAINT uq_descriptions_job_id UNIQUE (job_id),
    CONSTRAINT ck_descriptions_1 CHECK (status IN ('GENERATING', 'PUBLISHED', 'FAILED', 'ARCHIVED'))
);

CREATE TABLE characters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    description_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    aliases TEXT[],
    appearance TEXT,
    name_source VARCHAR(15),
    CONSTRAINT pk_characters PRIMARY KEY (id),
    CONSTRAINT uq_characters_description_id_name UNIQUE (description_id, name),
    CONSTRAINT ck_characters_1 CHECK (name_source IS NULL OR name_source IN ('DIALOGUE', 'SCREEN_TEXT', 'AI'))
);

CREATE TABLE transcript_segments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    description_id BIGINT NOT NULL,
    start_ms INTEGER NOT NULL,
    end_ms INTEGER NOT NULL,
    text TEXT NOT NULL,
    character_id BIGINT,
    CONSTRAINT pk_transcript_segments PRIMARY KEY (id),
    CONSTRAINT ck_transcript_segments_1 CHECK (end_ms >= start_ms)
);

CREATE TABLE scenes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    description_id BIGINT NOT NULL,
    scene_index INTEGER NOT NULL,
    start_ms INTEGER NOT NULL,
    end_ms INTEGER NOT NULL,
    title VARCHAR(100),
    scene_description TEXT NOT NULL,
    keyframe_key VARCHAR(500),
    CONSTRAINT pk_scenes PRIMARY KEY (id),
    CONSTRAINT uq_scenes_description_id_scene_index UNIQUE (description_id, scene_index),
    CONSTRAINT ck_scenes_1 CHECK (end_ms > start_ms),
    CONSTRAINT ex_scenes_no_overlap EXCLUDE USING gist (description_id WITH =, int4range(start_ms, end_ms) WITH &&)
);

CREATE TABLE screen_texts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    description_id BIGINT NOT NULL,
    start_ms INTEGER NOT NULL,
    end_ms INTEGER NOT NULL,
    text_type VARCHAR(15) NOT NULL DEFAULT 'OTHER',
    headline VARCHAR(300),
    full_text TEXT NOT NULL,
    summary_text TEXT,
    importance VARCHAR(6) NOT NULL,
    same_as_dialogue BOOLEAN NOT NULL DEFAULT FALSE,
    character_id BIGINT,
    CONSTRAINT pk_screen_texts PRIMARY KEY (id),
    CONSTRAINT ck_screen_texts_1 CHECK (text_type IN ('SUBTITLE', 'TITLE', 'SLIDE', 'TABLE', 'FORMULA', 'SCOREBOARD', 'NAME_TAG', 'UI', 'OTHER')),
    CONSTRAINT ck_screen_texts_2 CHECK (importance IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_screen_texts_3 CHECK (end_ms >= start_ms)
);

CREATE TABLE description_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    description_id BIGINT NOT NULL,
    line_index INTEGER NOT NULL,
    detail_level SMALLINT NOT NULL,
    start_ms INTEGER NOT NULL,
    gap_end_ms INTEGER,
    importance SMALLINT NOT NULL DEFAULT 2,
    text TEXT NOT NULL,
    voice_code VARCHAR(50),
    audio_key VARCHAR(500),
    audio_duration_ms INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_description_lines PRIMARY KEY (id),
    CONSTRAINT uq_description_lines_description_id_line_index_detail_level UNIQUE (description_id, line_index, detail_level),
    CONSTRAINT ck_description_lines_1 CHECK (detail_level BETWEEN 1 AND 3),
    CONSTRAINT ck_description_lines_2 CHECK (importance BETWEEN 1 AND 3),
    CONSTRAINT ck_description_lines_3 CHECK (gap_end_ms IS NULL OR gap_end_ms >= start_ms)
);

CREATE TABLE chapters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    description_id BIGINT NOT NULL,
    chapter_index INTEGER NOT NULL,
    start_ms INTEGER NOT NULL,
    end_ms INTEGER NOT NULL,
    title VARCHAR(100) NOT NULL,
    summary TEXT,
    keywords TEXT[],
    CONSTRAINT pk_chapters PRIMARY KEY (id),
    CONSTRAINT uq_chapters_description_id_chapter_index UNIQUE (description_id, chapter_index),
    CONSTRAINT ck_chapters_1 CHECK (end_ms > start_ms)
);

CREATE TABLE chat_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    video_id BIGINT,
    description_id BIGINT,
    video_time_ms INTEGER,
    input_mode VARCHAR(5) NOT NULL,
    utterance TEXT NOT NULL,
    intent VARCHAR(15) NOT NULL,
    target_ms INTEGER,
    target_chapter_id BIGINT,
    intent_latency_ms INTEGER,
    answer_text TEXT,
    answer_source VARCHAR(15),
    first_audio_ms INTEGER,
    total_latency_ms INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_chat_logs PRIMARY KEY (id),
    CONSTRAINT ck_chat_logs_1 CHECK (input_mode IN ('TEXT', 'VOICE')),
    CONSTRAINT ck_chat_logs_2 CHECK (intent IN ('QUESTION', 'SCENE_NOW', 'SEEK_SCENE', 'SEEK_TIME', 'SETTING', 'ACTION', 'UNKNOWN')),
    CONSTRAINT ck_chat_logs_3 CHECK (answer_source IS NULL OR answer_source IN ('STORED', 'FRAME', 'GEMINI_REQUERY', 'CACHE', 'UNANSWERABLE')),
    CONSTRAINT ck_chat_logs_answer CHECK (intent IN ('QUESTION', 'SCENE_NOW') OR (answer_text IS NULL AND answer_source IS NULL))
);

CREATE TABLE ai_call_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id BIGINT,
    chunk_id BIGINT,
    chat_log_id BIGINT,
    purpose VARCHAR(15) NOT NULL,
    model VARCHAR(50) NOT NULL,
    input_tokens INTEGER NOT NULL DEFAULT 0,
    output_tokens INTEGER NOT NULL DEFAULT 0,
    image_count SMALLINT NOT NULL DEFAULT 0,
    estimated_credits NUMERIC(10,2) NOT NULL DEFAULT 0,
    latency_ms INTEGER,
    is_fallback BOOLEAN NOT NULL DEFAULT FALSE,
    error_code VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_ai_call_logs PRIMARY KEY (id),
    CONSTRAINT ck_ai_call_logs_1 CHECK (purpose IN ('STT', 'DESCRIBE', 'SHORTEN', 'SUMMARY', 'CHAPTER', 'CLASSIFY', 'QUESTION', 'INTENT', 'TTS')),
    CONSTRAINT ck_ai_call_logs_target CHECK (num_nonnulls(job_id, chunk_id, chat_log_id) <= 1)
);

CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    line_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    reported_at_ms INTEGER NOT NULL,
    line_text_snapshot TEXT NOT NULL,
    reason VARCHAR(10) NOT NULL,
    reason_detail VARCHAR(500),
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    handled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_reports PRIMARY KEY (id),
    CONSTRAINT uq_reports_user_line UNIQUE (user_id, line_id),
    CONSTRAINT ck_reports_1 CHECK (reason IN ('WRONG', 'MISSING', 'OVERLAP', 'OTHER')),
    CONSTRAINT ck_reports_2 CHECK (status IN ('PENDING', 'RESOLVED', 'REJECTED'))
);

