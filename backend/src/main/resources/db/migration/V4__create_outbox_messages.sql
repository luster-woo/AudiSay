-- RabbitMQ 발행 보장용 Outbox. 발행할 메시지를 업무 데이터(jobs 등)와 같은 트랜잭션에 저장하고,
-- 커밋 후 발행해 브로커 확인(confirm)을 받으면 SENT로 바꾼다. 실패하면 PENDING으로 남아 재발행된다.

CREATE TABLE outbox_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    message_id UUID NOT NULL,
    exchange VARCHAR(100) NOT NULL,
    routing_key VARCHAR(100) NOT NULL,
    body JSONB NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    attempts SMALLINT NOT NULL DEFAULT 0,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    sent_at TIMESTAMPTZ,
    CONSTRAINT pk_outbox_messages PRIMARY KEY (id),
    CONSTRAINT uq_outbox_messages_message_id UNIQUE (message_id),
    CONSTRAINT ck_outbox_messages_1 CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE INDEX ix_outbox_messages_pending ON outbox_messages (created_at) WHERE status = 'PENDING';
