CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE scene_search_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    description_id BIGINT NOT NULL,
    source_type VARCHAR(10) NOT NULL,
    source_id BIGINT NOT NULL,
    start_ms INTEGER NOT NULL,
    text TEXT NOT NULL,
    model VARCHAR(50) NOT NULL,
    embedding vector(1536) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_scene_search_lines PRIMARY KEY (id),
    CONSTRAINT uq_scene_search_lines_source UNIQUE (description_id, source_type, source_id),
    CONSTRAINT ck_scene_search_lines_1 CHECK (source_type IN ('SCENE', 'NARRATION', 'DIALOGUE', 'SCREEN'))
);

CREATE TABLE scene_search_indexes (
    description_id BIGINT NOT NULL,
    model VARCHAR(50) NOT NULL,
    status VARCHAR(10) NOT NULL,
    line_count INTEGER NOT NULL DEFAULT 0,
    error_code VARCHAR(50),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_scene_search_indexes PRIMARY KEY (description_id),
    CONSTRAINT ck_scene_search_indexes_1 CHECK (status IN ('PENDING', 'DONE', 'FAILED'))
);

ALTER TABLE scene_search_lines ADD CONSTRAINT fk_descriptions_to_scene_search_lines
    FOREIGN KEY (description_id) REFERENCES descriptions (id) ON DELETE CASCADE;
ALTER TABLE scene_search_indexes ADD CONSTRAINT fk_descriptions_to_scene_search_indexes
    FOREIGN KEY (description_id) REFERENCES descriptions (id) ON DELETE CASCADE;

